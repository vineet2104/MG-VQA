# Type-specific constraints
# ---------------------------------------------------------------------------

def build_type_specific_constraint(question_type: str, q_desc: dict,
                                   mode: str = "agentic") -> str:
    """Return the constraint line for the given question type.

    These constraints are injected into the per-turn prompt to guide the
    VLM's tool-use strategy.
    """
    if question_type == "counting":
        target = q_desc.get("target_name", "the target")
        return (f"Do NOT remove any {target}. You may remove obstructors "
                f"to get a clearer count. Answer from one of the options.")
    elif question_type == "interactive_counting":
        return ("First remove objects, then count how many REMAIN. "
                "Any removal counts toward the manipulation budget.")
    elif question_type == "existence":
        return ('If you answer "yes", you MUST also provide "point": [row, col] '
                "on the object (grid [0,1000]). No point needed for \"no\".")
    elif question_type == "same_attribute":
        return ("Two target objects are designated A and B. Their normalized "
                "[row, col] positions are in the A/B TARGETS block below. "
                "A blank point means the object is occluded — clear obstructors "
                "until both points are populated before you answer.")
    elif question_type == "relative_size":
        return ("Two target objects are designated A and B. Their normalized "
                "[row, col] positions are in the A/B TARGETS block below. "
                "Answer which is larger AND provide \"ratio\": volume_A / "
                "volume_B. A blank point means the object is occluded — "
                "clear obstructors until both points are populated before "
                "you answer.")
    elif question_type == "marked_comparison":
        # Compare uses the rich "instructed" badge guidance as the default,
        # mode-adapted (agentic can manipulate; perception/direct cannot), plus
        # the nullable badge_points diagnostic request.  Kept consistent with
        # the agentic/perception per-turn constraint in reasoning_loop.py.
        from experiments.marked_size import question as _mq
        if mode in ("singlepass", "direct"):
            base = _mq.SINGLEPASS_INSTRUCTED_CONSTRAINT
        elif mode == "perception":
            base = _mq.PERCEPTION_INSTRUCTED_CONSTRAINT
        else:
            base = _mq.AGENTIC_INSTRUCTED_CONSTRAINT
        return base + " " + _mq.BADGE_REPORT_REQUEST
    elif question_type == "under_object":
        return ("You CANNOT see the hidden object from above. You MUST "
                "physically remove the cover object with grasp_and_remove "
                "BEFORE answering. Do NOT guess.")
    # ── Benchmark V2 tasks ─────────────────────────────────────────────
    elif question_type == "count":
        target = q_desc.get("target_name", "the target")
        if mode in ("direct", "singlepass"):
            return (f"Answer with a single non-negative INTEGER — the exact "
                    f"number of {target} on the table. You have a single image "
                    f"and no tools, so count from what is visible (some "
                    f"instances may be partly occluded). There are NO multiple-"
                    f"choice options; submit the integer as \"answer\".")
        if mode == "perception":
            return (f"Answer with a single non-negative INTEGER — the exact "
                    f"number of {target} on the table. You CANNOT move objects "
                    f"in this mode; count from what is visible (some instances "
                    f"may be partly occluded). There are NO multiple-choice "
                    f"options; submit the integer as \"answer\".")
        return (f"Answer with a single non-negative INTEGER — the exact number "
                f"of {target} on the table. Do NOT remove any {target}; you may "
                f"remove obstructors to see more clearly. There are NO multiple-"
                f"choice options; submit the integer as \"answer\".")
    elif question_type == "find":
        if mode in ("direct", "singlepass"):
            return ('If you answer "yes", you MUST also provide "point": [row, '
                    "col] on the object (grid [0,1000]). The point is checked "
                    "against the object's CURRENTLY VISIBLE mask. You have a "
                    "single image and no tools, so if the object is occluded "
                    "point at whatever part is visible. No point needed for "
                    '"no".')
        if mode == "perception":
            return ('If you answer "yes", you MUST also provide "point": [row, '
                    "col] on the object (grid [0,1000]). The point is checked "
                    "against the object's CURRENTLY VISIBLE mask. You CANNOT "
                    "move objects in this mode, so if the object is occluded "
                    "point at whatever part is visible. No point needed for "
                    '"no".')
        return ('If you answer "yes", you MUST also provide "point": [row, col] '
                "on the object (grid [0,1000]). The point is checked against the "
                "object's CURRENTLY VISIBLE mask, so if the object is occluded "
                "you must clear obstructors to expose it before pointing. "
                'No point needed for "no".')
    elif question_type == "beneath":
        if mode in ("direct", "singlepass"):
            return ("You have a single image and no tools, so you cannot see "
                    "under the cover — infer the hidden object from visible "
                    "cues (a protruding edge, the cover's shape, context). One "
                    "option is always \"none of the above\"; pick it only if "
                    "the truly hidden object is not among the concrete options.")
        if mode == "perception":
            return ("You CANNOT move the cover object in this mode, so you "
                    "cannot directly see what is underneath — infer the hidden "
                    "object from visible cues (a protruding edge, the cover's "
                    "shape, context). One option is always \"none of the "
                    "above\"; pick it only if the truly hidden object is not "
                    "among the concrete options.")
        return ("You CANNOT see the hidden object from above. You MUST "
                "physically remove the cover object with grasp_and_remove "
                "BEFORE answering. One option is always \"none of the above\" — "
                "pick it only if the truly hidden object is not among the "
                "concrete options.")
    elif question_type == "rearrangement":
        ref = q_desc.get("target_name", "the reference object")
        direction = q_desc.get("direction", "the specified side")
        return (f"Physically REMOVE (grasp_and_remove) every object on the "
                f"{direction} side of the {ref}, as seen in the top-down image. "
                f"Do NOT remove the {ref} itself, and do NOT remove objects on "
                f"other sides. When and only when the correct objects are gone, "
                f"call answer_question (no answer text needed — success is judged "
                f"by the final scene state).")
    return ""
