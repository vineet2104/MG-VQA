# Prompt templates live in mgvqa/prompt_templates/ (sibling of this module).
_PROMPT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "prompt_templates")


def load_system_prompt(mode: str) -> str:
    """Load the editable, model-independent system prompt for a release mode."""
    mode = "direct" if mode == "singlepass" else mode
    if mode not in {"direct", "perception", "agentic"}:
        raise ValueError(f"Unknown prompt mode: {mode}")
    return load_prompt(f"{mode}.txt")


def load_prompt(filename: str) -> str:
    """Load a prompt template from ``mgvqa/prompt_templates/``.

    Returns the raw text content of the file.
    """
    path = os.path.join(_PROMPT_DIR, filename)
    with open(path, "r") as f:
        return f.read()


# ---------------------------------------------------------------------------
# Release user prompts: explicit public inputs only, no question descriptor/GT.
# ---------------------------------------------------------------------------

def build_user_prompt(mode, *, question, question_type, answer_options=None,
                      step=1, max_steps=35, last_tool=None,
                      previous_tool_response="", remaining_budget=10,
                      max_actions=10, perception_calls=0,
                      has_segmentation_overlay=False):
    """Render one of three editable user templates (no search ablation).

    Values are substituted once: braces in questions/tool output stay literal.
    No target names, GT answers, visibility or badge coordinates are accepted.
    """
    from mgvqa.tool_registry import public_name
    mode = "direct" if mode == "singlepass" else mode
    if mode not in {"direct", "perception", "agentic"}:
        raise ValueError(f"Unknown prompt mode: {mode}")
    task = "compare" if question_type == "marked_comparison" else question_type
    options = list(answer_options or []) if task != "count" else []
    options_block = ("Answer options: " + ", ".join(str(x) for x in options)
                     if options else "")
    previous = ("Previous tool response:\n" + previous_tool_response.strip() + "\n"
                if step > 1 and previous_tool_response and mode != "direct" else "")
    return load_prompt(f"{mode}_user.txt").format(
        question=question, task=task, answer_options_block=options_block,
        step=step, max_steps=max_steps,
        last_tool=public_name(last_tool) if last_tool else "none",
        previous_tool_response_block=previous,
        remaining_budget=max(0, remaining_budget), max_actions=max_actions,
        perception_calls=perception_calls,
        segmentation_image_block=(
            "Two images are attached this turn: Image 1 is the usual clean top-down RGB; "
            "Image 2 is the segmentation tool's mask overlaid on its input RGB "
            "from the previous find_object call. "
            "The tinted region and numbered marker show the predicted selection, "
            "not ground truth. Use Image 1 for unobscured appearance."
            if has_segmentation_overlay and mode != "direct" else ""),
    ).strip()


def format_previous_tool_response(action, *, scene_graph_text="",
                                  segmentation_text="", has_grounding=False):
    """Serialize a public tool result, without GT object names or search hints.

    SG/segmentation text must come from perception outputs, not simulator GT.
    Manipulation action_history may contain simulator names: never emit them.
    """
    from mgvqa.tool_registry import canonical_name, public_name
    tool = canonical_name(action.get("tool", "error"))
    lines = [f"Tool: {public_name(tool)}"]
    if action.get("note"):
        # Validation/rejection messages are generated by the lifecycle handler.
        lines.append(str(action["note"]))
    if tool == "perceive_scene":
        lines.append(scene_graph_text or "Scene graph unavailable (perception failed).")
    elif tool == "perceive_find_object":
        # Do not echo labels/metadata, even if supplied by a backend. Identity
        # must be inferred from the RGB/overlay and the scene graph in context.
        lines.append("Object detected." if has_grounding and action.get("success")
                     else "No object detected; no valid selection.")
    elif tool == "grasp_and_remove":
        if action.get("success"):
            lines.append("Object placed in the clearing basket and removed from the scene.")
        elif action.get("grasp_outcome") == "grasped_slipped":
            lines.append("Object grasped and lifted but slipped before reaching the basket; not removed.")
        else:
            lines.append("Grasp unsuccessful or rejected; no removal confirmed. Objects may have shifted.")
        lines.append("Selection valid: " + ("yes" if has_grounding else "no"))
    elif tool == "push":
        lines.append(f"Direction: {action.get('direction', 'unspecified')}; "
                     f"distance_cm: {action.get('distance_cm', 10)}.")
        lines.append("Sweep executed; intended displacement is not guaranteed. Neighbouring objects may have moved."
                     if action.get("success") else "Push unsuccessful or rejected.")
        lines.append("Selection valid: " + ("yes" if has_grounding else "no"))
    elif tool == "error":
        lines.append("Response could not be parsed; return a single valid JSON object.")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Legacy perception-only prompt patching (not used by release templates)
# ---------------------------------------------------------------------------

def _replace_or_warn(text: str, old: str, new: str, label: str) -> str:
    """Replace ``old``→``new`` once; print a warning if the anchor is missing.

    Keeps prompt patching defensive: if a future edit to the V2 prompt breaks
    an anchor, we still apply the remaining patches (and surface the miss)
    rather than silently shipping a wrong prompt.
    """
    if old not in text:
        print(f"  [patch_v2_perception_only] WARN: anchor not found ({label}); "
              f"skipping this replacement.")
        return text
    return text.replace(old, new, 1)


def patch_v2_perception_only(system_prompt: str) -> str:
    """Turn the agentic V2 system prompt into a PERCEPTION-ONLY prompt.

    Programmatically strips the manipulation tools (grasp_and_remove, push),
    the manipulation-budget language, and the perception-loop FAILURE limit,
    and rewrites the tool enum / workflow / examples so the advertised toolset
    matches what perception mode actually offers: perceive_scene,
    perceive_find_object, answer_question.

    Patching (rather than a separate static file) keeps the agentic V2 prompt
    as the single source of truth — the two cannot drift.  See
    docs/THREE_MODE_EVAL_PLAN.md §3.
    """
    t = system_prompt

    # 1. Intro line — no manipulation.
    t = _replace_or_warn(
        t,
        "using tool calls to perceive or manipulate the scene as needed.",
        "using perception tool calls. IMPORTANT: in THIS mode you have NO "
        "manipulation tools — you CANNOT move, push, or remove any object. "
        "You must answer from the scene exactly as it is presented.",
        "intro")

    # 1b. Fix the perceive_scene / perceive_find_object descriptions that
    #     reference manipulation (contradictory in perception-only mode).
    t = _replace_or_warn(
        t,
        "   - Use this AFTER every manipulation (grasp/push) to update your "
        "understanding — every object's point is re-estimated for the NEW "
        "scene.\n"
        "   - Each object's point is accurate enough to act on directly: to "
        "grasp or push an object, copy its point straight into "
        "perceive_find_object. There is no separate \"coarse vs precise\" "
        "step — the scene graph point IS the grounding point.",
        "   - Each object's point is accurate enough to inspect directly: to "
        "examine one object closely, copy its point straight into "
        "perceive_find_object. There is no separate \"coarse vs precise\" "
        "step — the scene graph point IS the inspection point.",
        "perceive_scene-desc")
    t = _replace_or_warn(
        t,
        "   - Use this immediately BEFORE you want to MANIPULATE an object "
        "(grasp or push).\n"
        "   - Get the point from the scene graph: pick the object you want to "
        "act on and pass its `point` value verbatim. \n"
        "   - Point at ONE object at a time — the returned marker (object_id = "
        "1) is what you then pass to grasp_and_remove or push.\n",
        "   - Use this to INSPECT a single object closely (e.g. to confirm its "
        "identity or extent).\n"
        "   - Get the point from the scene graph: pick the object you want to "
        "inspect and pass its `point` value verbatim.\n"
        "   - Point at ONE object at a time.\n",
        "perceive_find_object-desc")

    # 2. Remove the grasp_and_remove (tool 3) and push (tool 4) blocks, and
    #    renumber answer_question 5→3.
    _tool3_start = "3. grasp_and_remove(object_id)"
    _tool5_start = "5. answer_question(answer)"
    i3 = t.find(_tool3_start)
    i5 = t.find(_tool5_start)
    if i3 != -1 and i5 != -1 and i5 > i3:
        t = t[:i3] + "3. answer_question(answer)" + t[i5 + len(_tool5_start):]
    else:
        print("  [patch_v2_perception_only] WARN: tool-block anchors not found; "
              "manipulation tools may still be advertised.")

    # 3. Budget line — perception mode has no manipulation budget.
    t = _replace_or_warn(
        t,
        "Perception is FREE (no budget cost). Only grasp_and_remove and push "
        "consume the manipulation budget.",
        "You have NO manipulation budget in this mode — perception "
        "(perceive_scene, perceive_find_object) and answering are your only "
        "available actions.",
        "budget")

    # 4. Recommended workflow — drop the manipulation steps.
    t = _replace_or_warn(
        t,
        "3. **If manipulation is needed** — pick the target object in the scene "
        "graph, call perceive_find_object with THAT object's point to segment "
        "it (marker object_id = 1), then grasp_and_remove or push it.\n"
        "4. **After manipulation** — call perceive_scene again to update your "
        "mental map (points are re-estimated for the new scene), then decide "
        "the next action.",
        "3. **Inspect more if useful** — call perceive_find_object on a "
        "specific object's point to segment it precisely, or perceive_scene "
        "again for a fresh overview. You cannot change the scene, so once you "
        "have enough evidence, answer.\n"
        "4. **Answer** — call answer_question as soon as the scene gives you "
        "enough information. You cannot reveal hidden objects, so reason from "
        "what is visible.",
        "workflow")

    # 5. Output-format tool enum.
    t = _replace_or_warn(
        t,
        '- "tool": one of "perceive_scene", "perceive_find_object", '
        '"grasp_and_remove", "push", "answer_question"',
        '- "tool": one of "perceive_scene", "perceive_find_object", '
        '"answer_question"',
        "tool-enum")

    # 6. Tool-specific fields — drop grasp/push lines.
    t = _replace_or_warn(
        t,
        '- grasp_and_remove: "object_id" (always 1 — the marker from the '
        'latest perceive_find_object)\n'
        '- push: "object_id" (1), "direction", optionally "distance_cm" '
        '(3-20, default 10)\n',
        "",
        "tool-fields")

    # 6b. Fix the perceive_find_object example (references removing/grasping).
    t = _replace_or_warn(
        t,
        '{"tool": "perceive_find_object", "point": [415, 300], "plan": '
        '"segment the gray box at its scene-graph point → remove it → '
        're-perceive → answer", "reasoning": "Scene graph shows the gray box '
        '(point [415, 300]) is on_top_of something — segment it to get a '
        'marker to grasp."}\n',
        '{"tool": "perceive_find_object", "point": [415, 300], "plan": '
        '"inspect the gray box at its scene-graph point → answer", '
        '"reasoning": "Scene graph shows a gray box at point [415, 300]; '
        'segment it to confirm its identity and extent."}\n',
        "ex-find")
    # 6c. Fix the perceive_scene example plan (mentions manipulate).
    t = _replace_or_warn(
        t,
        '"plan": "1. perceive_scene to understand layout, 2. answer if clear, '
        '3. else find_object(point) + manipulate"',
        '"plan": "1. perceive_scene to understand layout, 2. inspect specific '
        'objects with find_object(point) if unsure, 3. answer"',
        "ex-scene-plan")

    # 7. Examples — drop the grasp_and_remove and push example lines.
    for _ex_label, _ex in (
        ("ex-grasp",
         '{"tool": "grasp_and_remove", "object_id": 1, "plan": "remove cover '
         '✓ → perceive_scene → answer", "belief": "object under cover looked '
         'red", "reasoning": "Cover must be removed before I can see what\'s '
         'under it."}\n'),
        ("ex-push",
         '{"tool": "push", "object_id": 1, "direction": "left", "distance_cm": '
         '8, "plan": "push obstructor aside → perceive_scene → answer", '
         '"reasoning": "The segmented object is blocking the target; pushing '
         'it left should expose what\'s underneath."}\n'),
    ):
        t = _replace_or_warn(t, _ex, "", _ex_label)

    # 8. Hard constraints — remove the PERCEPTION LOOP LIMIT failure clause and
    #    replace with a perception-mode "answer when ready" note.
    t = _replace_or_warn(
        t,
        "- PERCEPTION LOOP LIMIT: You may call perception (perceive_scene or "
        "perceive_find_object) at most 5 times in a row without a manipulation "
        "action or an answer. On the 5th consecutive perception-only call the "
        "EPISODE ENDS IMMEDIATELY and is scored as a FAILURE (no answer). Do "
        "NOT keep perceiving — once you have enough information, either "
        "manipulate the scene or call answer_question.",
        "- ANSWER WHEN READY: perception does not change the scene, so repeated "
        "perception calls add nothing once you understand the layout. Inspect "
        "enough to be confident, then call answer_question. Some targets may be "
        "occluded and impossible to fully reveal in this mode — give your best "
        "grounded answer rather than perceiving indefinitely.",
        "hard-constraints")

    return t


